"""
Классификация новостей по типам событий.

Сознательно простые и прозрачные правила (основы слов + регулярные выражения):
каждое срабатывание можно объяснить, а качество проверяется ручной разметкой выборки.
Правила хранятся в configs/news.yaml; здесь - значения по умолчанию.

Два класса типов:
  local    - событие происходит в конкретном месте (нужна геопривязка): паводок, обстрел, отключение света…
  national - событие касается всей страны (геопривязка не нужна): ключевая ставка, цены на топливо…
"""
import re

LOCAL_EVENTS = {
    "flood": r"паводк|наводнен|подтоплен|затоплен|прорыв\w* дамб|уровень воды",
    "wildfire": r"(лесн|природн|ландшафтн|степн)\w* пожар|пал\w* травы",
    "fire": r"пожар|возгоран",
    "emergency_regime": r"режим\w* (чс|чрезвычайн|повышенной готовности)|чрезвычайн\w* ситуац",
    "drone_attack": r"бпла|беспилотник|\bдрон",
    "shelling": r"обстрел|ракетн\w* удар|ракетн\w* опасност|авиационн\w* опасност",
    "evacuation": r"эвакуац|эвакуир",
    "utility_outage": r"без (электричества|света|тепла|газа|воды|отопления)|отключен\w* (электр|свет|тепл|газ|вод)"
                      r"|обесточ|блэкаут|аварийн\w* отключ|порыв\w* (теплотрасс|водопровод)",
    "industrial_accident": r"взрыв|выброс\w* (вредн|опасн|аммиак|хлор)|утечк\w* (газа|аммиака|хлора)"
                           r"|разлив\w* (нефт|мазут|топлив)|обрушен",
    "terror": r"теракт|контртеррористическ",
    "transport_disruption": r"аэропорт\w*.{0,60}(ограничен|закрыт|приостанов)|перекрыт\w* (движен|трасс|дорог)"
                            r"|ограничен\w* движен|движение.{0,30}(закрыт|приостановлен|перекрыт)",
    "weather_extreme": r"аномальн\w* (жар|холод|мороз|снег|тепл)|сильн\w* (снегопад|мороз|ветер|ливн|дожд|жар)"
                       r"|ураган|смерч|метел|гололед|ледян\w* дожд",
    "epidemic": r"карантин|вспышк\w* (инфекц|заболеван|кишечн|кори|гриппа)|массов\w* отравлен",
    "enterprise_shock": r"(закрыт|остановк|банкротств)\w*.{0,30}(завод|предприяти|комбинат|фабрик|шахт|разрез)"
                        r"|массов\w* (увольнен|сокращен)|простой.{0,20}(завод|предприяти)",
}

NATIONAL_EVENTS = {
    "key_rate": r"ключев\w* ставк",
    "fuel_prices": r"цен\w* (на )?(бензин|топлив|дизел)|стоимост\w* (бензин|топлив)",
    "ruble_fx": r"курс\w* (рубл|доллар|евро|юан)",
    "marketplaces": r"маркетплейс|wildberries|вайлдберриз|\bozon|озон",
    "social_payments": r"индексаци\w* (пенси|пособ|выплат|мрот)|мрот",
    "sanctions": r"санкци",
}

# учения и прогнозы без реального события (снижает ложные срабатывания)
EXCLUDE = (r"учени[яй]|тренировк|\bвикторин|прогноз\w* погоды на"
           # дайджесты смешивают много сюжетов и дают ложные привязки
           r"|что (случилось|произошло) (этой ночью|за день|за неделю)|главное (за|к) |итоги (дня|недели)")


class EventClassifier:
    def __init__(self, local=None, national=None, exclude=None):
        self.local = {k: re.compile(v, re.I) for k, v in (local or LOCAL_EVENTS).items()}
        self.national = {k: re.compile(v, re.I) for k, v in (national or NATIONAL_EVENTS).items()}
        self.exclude = re.compile(exclude or EXCLUDE, re.I)

    @staticmethod
    def _prep(text: str) -> str:
        return text.lower().replace("ё", "е")

    def classify(self, text: str):
        """-> (список локальных типов, список национальных типов)"""
        t = self._prep(text)
        if self.exclude.search(t):
            return [], []
        loc = [k for k, rx in self.local.items() if rx.search(t)]
        if "wildfire" in loc and "fire" in loc:
            loc.remove("fire")
        nat = [k for k, rx in self.national.items() if rx.search(t)]
        return loc, nat
